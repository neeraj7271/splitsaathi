#!/usr/bin/env node
/**
 * Creates a production Android release keystore (once) and writes gitignored
 * apps/mobile/android/keystore.properties.
 *
 * Back up the .jks + passwords. Losing them means you can never update the
 * same app id in-place (users must uninstall).
 */
const { execSync } = require('node:child_process');
const crypto = require('node:crypto');
const fs = require('node:fs');
const path = require('node:path');

const androidDir = path.join(__dirname, '../apps/mobile/android');
const storeFileRel = 'app/splitsaathi-release.jks';
const storeFileAbs = path.join(androidDir, storeFileRel);
const propsPath = path.join(androidDir, 'keystore.properties');
const alias = 'splitsaathi';

if (fs.existsSync(storeFileAbs)) {
  console.error(`Keystore already exists: ${storeFileAbs}`);
  console.error('Delete it only if you intend to break updates for existing installs.');
  process.exit(1);
}

const password =
  process.env.SPLITSAATHI_UPLOAD_STORE_PASSWORD || crypto.randomBytes(18).toString('base64url');

const keytool = process.env.JAVA_HOME
  ? path.join(process.env.JAVA_HOME, 'bin', 'keytool')
  : 'keytool';

const dname = 'CN=SplitSaathi, OU=Mobile, O=SplitSaathi, L=India, ST=India, C=IN';

fs.mkdirSync(path.dirname(storeFileAbs), { recursive: true });

execSync(
  `"${keytool}" -genkeypair -v -storetype JKS` +
    ` -keystore "${storeFileAbs}"` +
    ` -alias ${alias}` +
    ` -keyalg RSA -keysize 2048 -validity 10000` +
    ` -dname "${dname}"` +
    ` -storepass "${password}"` +
    ` -keypass "${password}"`,
  { stdio: 'inherit' }
);

const props = [
  '# Generated by scripts/generate-release-keystore.js — gitignored. Back this up.',
  `storeFile=${storeFileRel}`,
  `storePassword=${password}`,
  `keyAlias=${alias}`,
  `keyPassword=${password}`,
  ''
].join('\n');

fs.writeFileSync(propsPath, props, { mode: 0o600 });

console.log(`\n✓ Created ${storeFileAbs}`);
console.log(`✓ Wrote ${propsPath}`);
console.log('\nKeep both files in a password manager / encrypted backup.');
console.log('Existing debug-signed installs cannot update over this APK — uninstall first.\n');
